let campaigns = SEED_CAMPAIGNS.map((item) => ({ ...item }));

export function getCampaigns() {
  return campaigns;
}

export function getCampaign(id) {
  return campaigns.find((item) => item.id === id) ?? null;
}

export function addCampaign(payload) {
  const campaign = {
    id: `cmp-${Date.now()}`,
    status: payload.scheduledAt ? 'scheduled' : 'draft',
    audience: Number(payload.audience) || 0,
    sent: 0,
    delivered: 0,
    opened: 0,
    clicked: 0,
    createdAt: new Date().toISOString(),
    imageUrl: null,
    ...payload,
  };
  campaigns = [campaign, ...campaigns];
  return campaign;
}

export function removeCampaigns(ids) {
  const remove = new Set(ids);
  campaigns = campaigns.filter((item) => !remove.has(item.id));
}

export function labelFor(list, id) {
  return list.find((item) => item.id === id)?.label ?? id;
}

export function statusMeta(id) {
  return CAMPAIGN_STATUSES.find((item) => item.id === id) ?? CAMPAIGN_STATUSES[0];
}

export function formatWhen(value) {
  if (!value) return 'Not scheduled';
  return new Date(value).toLocaleString('en-GB', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
}

export function formatInvoiceWhen(value) {
  if (!value) return '—';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  const day = String(date.getDate()).padStart(2, '0');
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const year = date.getFullYear();
  const minutes = String(date.getMinutes()).padStart(2, '0');
  return `${day}/${month}/${year}, ${date.getHours()}:${minutes}`;
}

export const CAMPAIGN_PAGE_SIZE = 5;

export function paginate(items, page, pageSize = CAMPAIGN_PAGE_SIZE) {
  const totalPages = Math.max(1, Math.ceil(items.length / pageSize));
  const current = Math.min(Math.max(page, 1), totalPages);
  const start = (current - 1) * pageSize;
  return { current, totalPages, rows: items.slice(start, start + pageSize) };
}

export function formatNumber(value) {
  return new Intl.NumberFormat('en-GB').format(value);
}

export function formatCreatedDate(value) {
  if (!value) return '—';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  const day = String(date.getDate()).padStart(2, '0');
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const year = String(date.getFullYear()).slice(-2);
  return `${day}-${month}-${year}`;
}

export function campaignInitials(name) {
  return String(name ?? '')
    .split(' ')
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0])
    .join('')
    .toUpperCase();
}

export function formatCedi(value) {
  if (value == null || value === '') return '—';
  return `GH₵${new Intl.NumberFormat('en-GH').format(value)}`;
}

